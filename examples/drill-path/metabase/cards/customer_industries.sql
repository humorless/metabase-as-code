SELECT
  CASE WHEN p.CATEGORY = {{industry}} THEN '★' ELSE '' END AS SELECTED,
  p.CATEGORY AS INDUSTRY,
  SUM(o.QUANTITY) AS UNITS,
  COUNT(DISTINCT p.ID) AS PRODUCTS,
  u.NAME AS CUSTOMER
FROM PUBLIC.ORDERS o
JOIN PUBLIC.PRODUCTS p ON p.ID = o.PRODUCT_ID
JOIN PUBLIC.PEOPLE u ON u.ID = o.USER_ID
WHERE u.NAME = {{customer}}
GROUP BY p.CATEGORY, u.NAME
ORDER BY UNITS DESC
