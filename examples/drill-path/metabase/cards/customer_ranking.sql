SELECT
  ROW_NUMBER() OVER (ORDER BY c.UNITS DESC, c.CUSTOMER) AS CUSTOMER_RANK,
  CASE WHEN 1 = 0 [[OR c.CUSTOMER = {{customer}}]] THEN '★' ELSE '' END AS SELECTED,
  c.CUSTOMER,
  c.UNITS,
  CAST(c.UNITS AS DOUBLE) / SUM(c.UNITS) OVER () AS UNIT_SHARE,
  c.ORDERS,
  '🥧' AS PRODUCT_MIX,
  c.INDUSTRY,
  CASE WHEN 1 = 0 [[OR c.CUSTOMER = {{customer}}]]
       THEN @@dashboard:dashboards/product_mix.json@@
       ELSE @@dashboard:dashboards/customers.json@@ END AS NEXT_DASHBOARD
FROM (
  SELECT p.CATEGORY AS INDUSTRY, u.NAME AS CUSTOMER, SUM(o.QUANTITY) AS UNITS, COUNT(*) AS ORDERS
  FROM PUBLIC.ORDERS o
  JOIN PUBLIC.PRODUCTS p ON p.ID = o.PRODUCT_ID
  JOIN PUBLIC.PEOPLE u ON u.ID = o.USER_ID
  WHERE p.CATEGORY = {{industry}}
  GROUP BY p.CATEGORY, u.NAME
) c
ORDER BY CUSTOMER_RANK
