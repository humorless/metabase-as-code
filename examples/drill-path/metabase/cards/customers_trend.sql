SELECT l.SHIP_QUARTER, l.CUSTOMER, SUM(l.UNITS) AS UNITS
FROM (
  SELECT
    t.SHIP_QUARTER,
    CASE WHEN t.CUSTOMER_RANK <= 10 [[OR t.CUSTOMER = {{customer}}]] THEN t.CUSTOMER ELSE 'Other' END AS CUSTOMER,
    t.UNITS
  FROM (
    SELECT q.*, DENSE_RANK() OVER (ORDER BY q.CUSTOMER_UNITS DESC, q.CUSTOMER) AS CUSTOMER_RANK
    FROM (
      SELECT
        DATE_TRUNC('QUARTER', o.CREATED_AT) AS SHIP_QUARTER,
        u.NAME AS CUSTOMER,
        SUM(o.QUANTITY) AS UNITS,
        SUM(SUM(o.QUANTITY)) OVER (PARTITION BY u.NAME) AS CUSTOMER_UNITS
      FROM PUBLIC.ORDERS o
      JOIN PUBLIC.PRODUCTS p ON p.ID = o.PRODUCT_ID
      JOIN PUBLIC.PEOPLE u ON u.ID = o.USER_ID
      WHERE p.CATEGORY = {{industry}}
      GROUP BY DATE_TRUNC('QUARTER', o.CREATED_AT), u.NAME
    ) q
  ) t
) l
GROUP BY l.SHIP_QUARTER, l.CUSTOMER
ORDER BY l.SHIP_QUARTER, l.CUSTOMER
